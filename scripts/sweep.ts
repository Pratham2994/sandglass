/**
 * Spread sweep: does a reaction carry on through the whole thing, or stall?
 * For every element that burns or explodes, a long one-cell strip and a solid
 * block are lit at one end, the way that element is meant to be lit (a flame;
 * great heat if a flame cannot light it). The sweep records whether fire
 * reaches the far end of the strip and how much of the block ever burns.
 * This catches bugs where a reaction starts but does not carry on, like a C4
 * strip that only blew up near the spark, or a gunpowder trail that died.
 * Gases and living things are left out (they drift or grow). Writes
 * docs/SWEEP.md. Run: npm run sweep
 */
import { writeFileSync } from 'node:fs';
import { ELEMENTS, EMPTY, FIRE, HABITAT_OF, IGNITION_OF, NO_FLAME_OF, PHASE_OF, PH_ENERGY, PH_GAS, WITHER_INTO_OF, elementId } from '../src/sim/elements';
import { step } from '../src/sim/step';
import { World } from '../src/sim/world';

const W = 96;
const H = 48;
const FRAMES = 1200;
const WALL = elementId('wall');

interface Result {
  name: string;
  /** Strip outcome: reached the far end, still spreading at the end of the run, or stalled with fuel ahead. */
  outcome: 'reached' | 'spreading' | 'stalled';
  /** Frame it reached the end, or the column where it stalled or had got to. */
  at: number;
  block: number;
}
/** No forward progress for this long, with fuel still ahead, counts as a stall. */
const STALL = 180;

/** Lights the cell at (x, y): a flame above it, or great heat if a flame cannot light it (held for 1 s, like a torch). */
function light(world: World, id: number, x: number, y: number): void {
  if (NO_FLAME_OF[id] !== 0) {
    world.temp[y * W + x] = IGNITION_OF[id] + 100;
    world.wake(x, y);
  } else world.place((y - 1) * W + x, FIRE);
}

/** Is there fire (a flame, or a burning or exploding cell) within the box? */
function fireIn(world: World, x0: number, x1: number, y0: number, y1: number): boolean {
  for (let y = y0; y <= y1; y++) for (let x = x0; x <= x1; x++) if (PHASE_OF[world.type[y * W + x]] === PH_ENERGY) return true;
  return false;
}

/** A strip one cell high from x = 4 to 91 on a wall floor, lit at its left end. */
function strip(id: number): { outcome: Result['outcome']; at: number } {
  const world = new World(W, H, 5 + id);
  for (let x = 0; x < W; x++) for (let y = H - 4; y < H; y++) world.place(y * W + x, WALL);
  const y = H - 5;
  for (let x = 4; x < 92; x++) world.place(y * W + x, id);
  light(world, id, 4, y);
  let front = 4;
  let lastMove = 0;
  for (let f = 1; f <= FRAMES; f++) {
    if (f <= 60 && NO_FLAME_OF[id] !== 0 && world.type[y * W + 4] === id) light(world, id, 4, y);
    step(world);
    if (fireIn(world, 86, 95, y - 4, y)) return { outcome: 'reached', at: f };
    // The front: the furthest column with fire near the strip.
    for (let x = W - 1; x > front; x--)
      if (fireIn(world, x, x, y - 2, y)) {
        front = x;
        lastMove = f;
        break;
      }
    if (f - lastMove > STALL) {
      // Stalled only if there is still unburnt fuel ahead of the front.
      let ahead = 0;
      for (let x = front + 1; x < 92; x++) if (world.type[y * W + x] === id) ahead++;
      if (ahead > 0) return { outcome: 'stalled', at: front };
    }
  }
  return { outcome: 'spreading', at: front };
}

/** A block 40 wide and 12 high, lit at its top left corner; returns the share of its cells that ever burned. */
function block(id: number): number {
  const world = new World(W, H, 9 + id);
  for (let x = 0; x < W; x++) for (let y = H - 4; y < H; y++) world.place(y * W + x, WALL);
  const x0 = 20;
  const y0 = H - 16;
  for (let y = y0; y < H - 4; y++) for (let x = x0; x < x0 + 40; x++) world.place(y * W + x, id);
  light(world, id, x0, y0);
  const burned = new Uint8Array(40 * 12);
  for (let f = 1; f <= FRAMES; f++) {
    if (f <= 60 && NO_FLAME_OF[id] !== 0 && world.type[y0 * W + x0] === id) light(world, id, x0, y0);
    step(world);
    for (let y = 0; y < 12; y++)
      for (let x = 0; x < 40; x++) if (PHASE_OF[world.type[(y0 + y) * W + x0 + x]] === PH_ENERGY || world.type[(y0 + y) * W + x0 + x] === EMPTY) burned[y * 40 + x] = 1;
  }
  return burned.reduce((n, b) => n + b, 0) / burned.length;
}

const results: Result[] = [];
for (let id = 1; id < ELEMENTS.length; id++) {
  const ph = PHASE_OF[id];
  if (IGNITION_OF[id] === Infinity || ph === PH_GAS || ph === PH_ENERGY || HABITAT_OF[id] !== 0 || WITHER_INTO_OF[id] !== 0) continue;
  const s = strip(id);
  results.push({ name: ELEMENTS[id].name, outcome: s.outcome, at: s.at, block: block(id) });
}
const rank = { stalled: 0, spreading: 1, reached: 2 };
results.sort((a, b) => rank[a.outcome] - rank[b.outcome] || a.block - b.block);
const stalls = results.filter((r) => r.outcome === 'stalled');

const out: string[] = [];
out.push('# Sandglass spread sweep');
out.push('');
out.push('Generated by `npm run sweep`. Every element that burns or explodes (not gases or living things) is built as a long one-cell strip (88 cells) and as a solid block, lit at one end the way it is meant to be lit (a flame, or great heat when a flame cannot light it), and watched for 20 s. A strip whose fire stops moving for 3 s while fuel is still ahead is flagged as **stalled**: that is the bug this sweep exists to catch (a C4 strip that only went off near the spark, a gunpowder trail that died). "Still spreading" is a slow but steady fire, which is realistic for wood or paper. Elements that melt or char before they burn (wax, plastic, cooked meat) show as stalled or 0% when nothing burns: check those against their descriptions.');
out.push('');
out.push(`- Elements swept: ${results.length}`);
out.push(`- Stalled: ${stalls.length}`);
out.push('');
out.push('| | Element | Strip | Block: share that burned |');
out.push('| --- | --- | --- | --- |');
for (const r of results) {
  const what = r.outcome === 'reached' ? `reached the end after ${(r.at / 60).toFixed(1)} s` : r.outcome === 'spreading' ? `still spreading, at cell ${r.at - 4} of 88` : `**stalled** at cell ${r.at - 4} of 88`;
  out.push(`| ${r.outcome === 'stalled' ? '**check**' : 'ok'} | ${r.name} | ${what} | ${Math.round(r.block * 100)}% |`);
}
out.push('');
writeFileSync(new URL('../docs/SWEEP.md', import.meta.url), out.join('\n'));
for (const r of stalls) console.log(`stalled ${r.name}: at cell ${r.at - 4} of 88, block ${Math.round(r.block * 100)}%`);
console.log(`Sweep: ${results.length} elements, ${stalls.length} stalled. Wrote docs/SWEEP.md.`);
