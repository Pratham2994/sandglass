/**
 * Soak test: random worlds, left to run, checked for anything that should
 * never happen. Each world mixes a handful of random elements in random
 * blobs (some hot, some cold, on a wall floor), runs 20 s of game time, and
 * every second checks: every temperature finite and within limits, every
 * cell a real element, every circuit voltage finite, and no crash. Each
 * world is then run again from the same seed and must end with the same
 * grid hash (determinism). Writes docs/SOAK.md; exits 1 on any failure.
 * Run: npm run soak
 */
import { writeFileSync } from 'node:fs';
import { ELEMENTS, ELEMENT_COUNT, EMPTY } from '../src/sim/elements';
import { step } from '../src/sim/step';
import { World } from '../src/sim/world';
import { Rng } from '../src/sim/rng';

const W = 120;
const H = 80;
/** How many worlds, and where their seeds start (SOAK_WORLDS, SOAK_FROM to explore more). */
const WORLDS = Number(process.env.SOAK_WORLDS ?? 40);
const FROM = Number(process.env.SOAK_FROM ?? 0);
const ELEMENTS_EACH = 6;
const FRAMES = 1200;
const T_MIN = -273;
const T_MAX = 5000;

/** Builds world `n`: a wall floor and random blobs of random elements. */
function build(n: number): { world: World; keys: string[] } {
  const world = new World(W, H, 1000 + n);
  const pick = new Rng(77 + n * 31);
  for (let x = 0; x < W; x++) for (let y = H - 3; y < H; y++) world.place(y * W + x, 1);
  const keys: string[] = [];
  for (let k = 0; k < ELEMENTS_EACH; k++) {
    const id = 1 + (pick.nextU32() % (ELEMENT_COUNT - 1));
    keys.push(ELEMENTS[id].key);
    const cx = 8 + (pick.nextU32() % (W - 16));
    const cy = 8 + (pick.nextU32() % (H - 20));
    const r = 2 + (pick.nextU32() % 7);
    const heat = pick.nextU32() % 4 === 0 ? 600 + (pick.nextU32() % 1200) : pick.nextU32() % 6 === 0 ? -150 : NaN;
    for (let y = cy - r; y <= cy + r; y++)
      for (let x = cx - r; x <= cx + r; x++) {
        if ((x - cx) ** 2 + (y - cy) ** 2 > r * r || world.type[y * W + x] !== EMPTY) continue;
        world.place(y * W + x, id);
        if (heat === heat) world.temp[y * W + x] = heat;
      }
  }
  return { world, keys };
}

/** First broken invariant in the world, or null. */
function broken(world: World): string | null {
  for (let i = 0; i < world.size; i++) {
    const T = world.temp[i];
    if (!(T >= T_MIN && T <= T_MAX)) return `temperature ${T} at cell ${i % W},${(i / W) | 0} (${ELEMENTS[world.type[i]]?.key})`;
    if (world.type[i] >= ELEMENT_COUNT) return `unknown element id ${world.type[i]} at ${i % W},${(i / W) | 0}`;
    if (world.solute[i] >= ELEMENT_COUNT) return `unknown solute id ${world.solute[i]} at ${i % W},${(i / W) | 0}`;
    if (!Number.isFinite(world.volt[i])) return `voltage ${world.volt[i]} at ${i % W},${(i / W) | 0}`;
  }
  return null;
}

const rows: string[] = [];
let failures = 0;
const t0 = Date.now();
for (let n = FROM; n < FROM + WORLDS; n++) {
  const { world, keys } = build(n);
  let problem: string | null = null;
  try {
    for (let f = 1; f <= FRAMES && !problem; f++) {
      step(world);
      if (f % 60 === 0) problem = broken(world);
    }
  } catch (err) {
    problem = `crash: ${(err as Error).message}`;
  }
  if (!problem) {
    const again = build(n).world;
    for (let f = 1; f <= FRAMES; f++) step(again);
    if (again.hash() !== world.hash()) problem = `not deterministic: ${world.hash()} then ${again.hash()}`;
  }
  if (problem) failures++;
  rows.push(`| ${n} | ${keys.join(', ')} | ${problem ? `**${problem}**` : 'ok'} |`);
  console.log(`${n}: ${problem ?? 'ok'}  (${keys.join(', ')})`);
}
const secs = ((Date.now() - t0) / 1000).toFixed(0);
const head = [
  '# Soak test',
  '',
  'Generated by `npm run soak`. Random worlds of mixed elements, each run for 20 s of game time, checked every second for impossible states, then run again from the same seed for an identical result.',
  '',
  `- Worlds: ${WORLDS}, ${ELEMENTS_EACH} elements each, ${W} × ${H} cells`,
  `- Failures: ${failures}`,
  `- Time: ${secs} s`,
  '',
  '| World | Elements | Result |',
  '| --- | --- | --- |',
];
writeFileSync('docs/SOAK.md', [...head, ...rows, ''].join('\n'));
console.log(`Soak: ${WORLDS - failures}/${WORLDS} worlds clean. Wrote docs/SOAK.md.`);
if (failures) process.exit(1);
